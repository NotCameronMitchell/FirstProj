export const SPRITE_IDS = Object.keys(DEFS);

export interface Sprite {
  w: number;
  h: number;
  normal: HTMLCanvasElement;
  flipped: HTMLCanvasElement;
  white: HTMLCanvasElement;
  whiteFlipped: HTMLCanvasElement;
}

const cache = new Map<string, Sprite>();

/** Returns grid problems (row width mismatches, unknown palette keys); used by tests. */
export function validateSprites(): string[] {
  const problems: string[] = [];
  for (const [id, d] of Object.entries(DEFS)) {
    const w = d.grid[0].length;
    d.grid.forEach((row, y) => {
      if (row.length !== w) problems.push(`${id} row ${y} has ${row.length} chars, expected ${w}`);
      for (const ch of row) if (ch !== '.' && ch !== 'o' && !(ch in d.pal)) problems.push(`${id} uses '${ch}' with no colour`);
    });
  }
  return [...new Set(problems)];
}

function paint(d: SpriteDef, flip: boolean, white: boolean): HTMLCanvasElement {
  const h = d.grid.length;
  const w = d.grid[0].length;
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const ctx = c.getContext('2d')!;
  for (let y = 0; y < h; y++) {
    const row = d.grid[y];
    for (let x = 0; x < w; x++) {
      const ch = row[x];
      if (!ch || ch === '.') continue;
      ctx.fillStyle = white ? (ch === 'o' ? '#ffffff' : '#fff6e8') : ch === 'o' ? OUTLINE : (d.pal as Palette)[ch] ?? '#ff00ff';
      ctx.fillRect(flip ? w - 1 - x : x, y, 1, 1);
    }
  }
  return c;
}

export function getSprite(id: string): Sprite {
  let s = cache.get(id);
  if (!s) {
    const d = DEFS[id] ?? DEFS.hollow;
    s = {
      w: d.grid[0].length,
      h: d.grid.length,
      normal: paint(d, false, false),
      flipped: paint(d, true, false),
      white: paint(d, false, true),
      whiteFlipped: paint(d, true, true),
    };
    cache.set(id, s);
  }
  return s;
}
